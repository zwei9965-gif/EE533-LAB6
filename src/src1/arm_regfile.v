`timescale 1ns/1ps
module arm_regfile (
    input  wire        clk,
    input  wire        rst,
    // ?????? + write-through bypass?
    input  wire [3:0]  r0addr,
    output wire [31:0] r0data,
    input  wire [3:0]  r1addr,
    output wire [31:0] r1data,
    // ???1????? (DP/LDR ??)
    input  wire        we,
    input  wire [3:0]  waddr,
    input  wire [31:0] wdata,
    // ???2????? (pre/post-index Rn ??)
    input  wire        we2,
    input  wire [3:0]  waddr2,
    input  wire [31:0] wdata2
);
    reg [31:0] regs [0:15];
    integer i;

    // ?? ????write-through bypass ?????????????????????????
    // ????WB2 > WB1 > ????
    // ?? ID ??? WB ????????????
    assign r0data = (we2 && waddr2 == r0addr) ? wdata2 :
                    (we  && waddr  == r0addr) ? wdata  : regs[r0addr];
    assign r1data = (we2 && waddr2 == r1addr) ? wdata2 :
                    (we  && waddr  == r1addr) ? wdata  : regs[r1addr];

    // ?? ????????????????????????????????????????????
    always @(posedge clk) begin
        if (rst) begin
            for (i = 0; i < 16; i = i + 1)
                regs[i] <= 32'b0;
        end else begin
            if (we)
                regs[waddr]  <= wdata;
            if (we2)
                regs[waddr2] <= wdata2;
        end
    end
endmodule